"""SportyBet booking workflow.

No public booking-code API is configured. This module never invents a code,
never places a wager, and never tries to bypass an access challenge.
"""

import json
import uuid
from datetime import datetime, timezone

from accumulator_engine import export_ticket, revalidate_ticket

BOOKMAKER = 'SportyBet'


def integration_status():
    return {
        'bookmaker': BOOKMAKER,
        'automatic_booking_code': False,
        'automatic_wager_placement': False,
        'booking_module': 'installed',
        'manual_registration': True,
        'supervised_browser': True,
        'unattended_collection': False,
        'verified': False,
        'reason': (
            'Displayed SportyBet prices are collected from the public page. '
            'A booking code is requested only for a qualified ticket, only during 07:00–08:00, 12:00–13:00 or 17:00–18:00 WAT, '
            'and only by clicking the booking-code control. The code is stored only when the page shows it. '
            'No wager is placed, and no code is invented.'
        ),
    }


def prepare_betslip(connection, ticket_id):
    ticket = connection.execute(
        'SELECT id,status,combined_odds,sport_mode,tier,probability_basis FROM sports_ai_accumulator_tickets WHERE id=?',
        (ticket_id,),
    ).fetchone()
    if not ticket:
        return None
    legs = [dict(row) for row in connection.execute(
        """SELECT fixture_id,sport,competition,home,away,starts_at,market,selection,decimal_odds,bookmaker,odds_observed_at
           FROM sports_ai_accumulator_legs WHERE ticket_id=? ORDER BY starts_at""",
        (ticket_id,),
    )]
    return {
        'ticket_id': ticket_id,
        'bookmaker': BOOKMAKER,
        'automation': 'unavailable',
        'booking_code': None,
        'places_wager': False,
        'status': ticket['status'],
        'tier': ticket['tier'],
        'combined_odds': ticket['combined_odds'],
        'probability_basis': ticket['probability_basis'],
        'selections': legs,
        'instructions': (
            'Enter these stored selections in SportyBet yourself if the prices still match. '
            'If SportyBet gives you a booking code, paste that exact code into the manual register. '
            'This screen does not create a code and does not submit a bet.'
        ),
        'integration': integration_status(),
    }


def register_manual_code(connection, actor, audit, ticket_id, code, evidence, now=None):
    """Store a user-supplied code after revalidation. The code is not checked with SportyBet."""
    cleaned = (code or '').strip()
    if len(cleaned) < 2:
        return {'error': 'Enter the booking code SportyBet gave you'}
    if cleaned.lower() in {'auto', 'generated', 'sportybet', 'placeholder'}:
        return {'error': 'A placeholder is not a booking code'}
    check = revalidate_ticket(connection, ticket_id, now)
    if check is None:
        return None
    if not check['ok']:
        _log(connection, ticket_id, 'booking_blocked', {'revalidation': check, 'automation': 'unavailable'})
        return {'error': 'Booking code was not stored because the ticket failed revalidation', 'revalidation': check}
    from qualification_engine import ticket_is_bookable
    if not ticket_is_bookable(connection, ticket_id):
        _log(connection, ticket_id, 'booking_blocked', {'reason_code': 'QUALIFICATION_REQUIRED'})
        return {'error': 'Booking code was not stored because a leg has no current QUALIFIED decision'}
    existing = connection.execute(
        """SELECT code,status,created_at FROM sports_ai_booking_codes
           WHERE accumulator_ticket_id=? ORDER BY created_at DESC LIMIT 1""",
        (ticket_id,),
    ).fetchone()
    connection.execute(
        """INSERT INTO sports_ai_booking_codes
           (id,ticket_id,accumulator_ticket_id,code,verification_method,evidence,status,bookmaker,integration_status)
           VALUES(?,?,?,?,?,?,?,?,?)""",
        (
            str(uuid.uuid4()), None, ticket_id, cleaned, 'manual', evidence.strip(),
            'unverified', BOOKMAKER, 'manual_only',
        ),
    )
    _log(connection, ticket_id, 'booking_code_registered', {
        'bookmaker': BOOKMAKER,
        'verification_method': 'manual',
        'status': 'unverified',
        'automation': 'unavailable',
        'previous_code_stored': bool(existing),
        'note': 'User-supplied code. SportyBet was not contacted and the code was not generated by CACSMS.',
    })
    if audit:
        audit(connection, actor, 'accumulator.booking_code', {'ticket_id': ticket_id, 'status': 'unverified'})
    return {
        'status': 'unverified',
        'bookmaker': BOOKMAKER,
        'code': cleaned,
        'automation': 'unavailable',
        'message': 'Manually recorded. SportyBet was not contacted, so this code is not independently validated.',
        'revalidation': check,
    }


def list_codes(connection, accumulator_only=False):
    query = """SELECT id,ticket_id,accumulator_ticket_id,code,verification_method,evidence,status,
                      bookmaker,expires_at,verified_at,integration_status,created_at
               FROM sports_ai_booking_codes"""
    if accumulator_only:
        query += ' WHERE accumulator_ticket_id IS NOT NULL'
    query += ' ORDER BY created_at DESC LIMIT 200'
    return [dict(row) for row in connection.execute(query)]


def _log(connection, ticket_id, event_type, details):
    connection.execute(
        """INSERT INTO sports_ai_ticket_monitoring_events
           (id,ticket_id,event_type,details_json,created_at) VALUES(?,?,?,?,?)""",
        (str(uuid.uuid4()), ticket_id, event_type, json.dumps(details), datetime.now(timezone.utc).isoformat()),
    )


def automatic_booking_code(ticket_id):
    """The only supported answer until an authorized integration exists."""
    return {
        'ticket_id': ticket_id,
        'booking_code': None,
        'requested': False,
        'integration': integration_status(),
    }
