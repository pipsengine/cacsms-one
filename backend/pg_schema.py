"""SQLite schema -> PostgreSQL DDL.

The SQLite migrations in /migrations stay the single source of truth for the schema. For a new
PostgreSQL schema, `build_schema_statements()` replays every migration into an in-memory SQLite
database and translates the resulting tables, indexes and triggers. For an existing PostgreSQL
schema, `translate_migration()` translates a newly added migration file statement by statement.

Type mapping keeps Python-visible values identical to SQLite's:
  INTEGER -> BIGINT, REAL -> DOUBLE PRECISION, everything else -> TEXT (timestamps stay ISO text).
Every table also gets a `rowid` BIGINT identity column, because the code orders and windows by
SQLite's implicit rowid (insertion order).
"""
import re
import sqlite3
from pathlib import Path

MIGRATIONS = Path(__file__).resolve().parent.parent / 'migrations'
NOW_DEFAULT = 'sqlite_compat.sqlite_now()'
# Columns whose stored values do not fit their declared SQLite type (found by a typeof() audit of
# the live database). NUMERIC loads as int when whole and float otherwise, as SQLite returned it.
COLUMN_TYPES = {
    ('sports_ai_accumulator_tickets', 'tier'): 'NUMERIC',      # target-odds tier; 1.5 is a tier
    ('sports_ai_accumulator_performance', 'tier'): 'NUMERIC',
}

_FK_ACTION = r'(?:\s+ON\s+(?:DELETE|UPDATE)\s+(?:SET\s+NULL|SET\s+DEFAULT|CASCADE|RESTRICT|NO\s+ACTION))*'
_DEFERRABLE = r'(?:\s+(?:NOT\s+)?DEFERRABLE(?:\s+INITIALLY\s+(?:DEFERRED|IMMEDIATE))?)?'
_INLINE_FK = re.compile(r'\s+REFERENCES\s+"?\w+"?\s*(?:\([^)]*\))?' + _FK_ACTION + _DEFERRABLE, re.I)
_TABLE_FK = re.compile(r',\s*(?:CONSTRAINT\s+\w+\s+)?FOREIGN\s+KEY\s*\([^)]*\)\s*REFERENCES\s+"?\w+"?\s*(?:\([^)]*\))?'
                       + _FK_ACTION + _DEFERRABLE, re.I)
_TRIGGER = re.compile(
    r"CREATE\s+TRIGGER\s+(?:IF\s+NOT\s+EXISTS\s+)?\"?(\w+)\"?\s+(BEFORE|AFTER)\s+(DELETE|UPDATE|INSERT)\s+ON\s+\"?(\w+)\"?"
    r"\s+(?:FOR\s+EACH\s+ROW\s+)?BEGIN\s+SELECT\s+RAISE\s*\(\s*ABORT\s*,\s*'((?:[^']|'')*)'\s*\)\s*;\s*END",
    re.I | re.S)


def _outside_quotes(sql, transform):
    """Apply `transform` to the parts of `sql` that are not inside '...' string literals."""
    parts = re.split(r"('(?:[^']|'')*')", sql)
    return ''.join(part if index % 2 else transform(part) for index, part in enumerate(parts))


def _types(text):
    text = re.sub(r'\bINTEGER\s+PRIMARY\s+KEY\s+AUTOINCREMENT\b',
                  'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', text, flags=re.I)
    text = re.sub(r'\bINTEGER\s+PRIMARY\s+KEY\b', 'BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY', text, flags=re.I)
    text = re.sub(r'\bINTEGER\b|\bINT\b|\bBOOLEAN\b', 'BIGINT', text, flags=re.I)
    text = re.sub(r'\bREAL\b|\bFLOAT\b|\bDOUBLE\b(?!\s+PRECISION)|\bNUMERIC\b', 'DOUBLE PRECISION', text, flags=re.I)
    text = re.sub(r'\bDATETIME\b|\bTIMESTAMP\b(?!\s*\()', 'TEXT', text, flags=re.I)
    text = re.sub(r'DEFAULT\s+CURRENT_TIMESTAMP', 'DEFAULT ' + NOW_DEFAULT, text, flags=re.I)
    text = re.sub(r'DEFAULT\s+\(\s*datetime\s*\(\s*\'now\'\s*\)\s*\)', 'DEFAULT ' + NOW_DEFAULT, text, flags=re.I)
    return text


def table_ddl(create_sql, with_foreign_keys=False):
    """CREATE TABLE in PostgreSQL form, with the rowid identity column added."""
    sql = create_sql.strip().rstrip(';')
    sql = re.sub(r'^CREATE\s+TABLE\s+(?!IF\s+NOT\s+EXISTS)', 'CREATE TABLE IF NOT EXISTS ', sql, flags=re.I)
    if not with_foreign_keys:
        sql = _outside_quotes(sql, lambda part: _INLINE_FK.sub('', _TABLE_FK.sub('', part)))
    sql = _outside_quotes(sql, _types)
    name = re.match(r'CREATE\s+TABLE\s+IF\s+NOT\s+EXISTS\s+"?(\w+)"?', sql, re.I).group(1)
    for (table, column), kind in COLUMN_TYPES.items():
        if table == name:
            sql = re.sub(rf'(\(|,)(\s*"?{column}"?\s+)BIGINT\b', rf'\1\2{kind}', sql, count=1)
    close = sql.rfind(')')
    return sql[:close].rstrip() + ',\n rowid BIGINT GENERATED BY DEFAULT AS IDENTITY' + sql[close:]


def index_ddl(create_sql):
    sql = create_sql.strip().rstrip(';')
    sql = re.sub(r'^CREATE\s+(UNIQUE\s+)?INDEX\s+(?!IF\s+NOT\s+EXISTS)', r'CREATE \1INDEX IF NOT EXISTS ', sql, flags=re.I)
    return _outside_quotes(sql, _types)


def trigger_ddl(create_sql):
    match = _TRIGGER.search(create_sql)
    if not match:
        raise ValueError(f'Unsupported trigger: {create_sql[:120]}')
    name, timing, event, table, message = match.groups()
    # ENABLE ALWAYS: evidence stays immutable even in a session that switched foreign keys off
    # (session_replication_role = replica, which otherwise skips triggers).
    return [f'DROP TRIGGER IF EXISTS {name} ON {table}',
            f"CREATE TRIGGER {name} {timing} {event} ON {table} FOR EACH ROW "
            f"EXECUTE FUNCTION sqlite_compat.raise_immutable('{message}')",
            f'ALTER TABLE {table} ENABLE ALWAYS TRIGGER {name}']


def foreign_key_ddl(connection, table, not_valid=False):
    """ALTER TABLE ... ADD FOREIGN KEY from a SQLite connection's PRAGMA foreign_key_list."""
    groups = {}
    for row in connection.execute(f'PRAGMA foreign_key_list("{table}")'):
        fk_id, _seq, parent, child_col, parent_col, on_update, on_delete = row[:7]
        entry = groups.setdefault(fk_id, {'parent': parent, 'child': [], 'parent_cols': [],
                                          'on_update': on_update, 'on_delete': on_delete})
        entry['child'].append(child_col)
        entry['parent_cols'].append(parent_col)
    statements = []
    for fk_id, entry in sorted(groups.items()):
        name = f'{table}_fk{fk_id}'
        parent_cols = entry['parent_cols'] if all(entry['parent_cols']) else ['id']
        clause = (f'ALTER TABLE {table} ADD CONSTRAINT {name} FOREIGN KEY ({", ".join(entry["child"])}) '
                  f'REFERENCES {entry["parent"]} ({", ".join(parent_cols)})')
        for kind in ('delete', 'update'):
            action = (entry[f'on_{kind}'] or 'NO ACTION').upper()
            if action != 'NO ACTION':
                clause += f' ON {kind.upper()} {action}'
        statements.append((name, clause + (' NOT VALID' if not_valid else '')))
    return statements


def split_statements(sql):
    statements, current = [], ''
    for line in sql.splitlines():
        current += line + '\n'
        if sqlite3.complete_statement(current):
            if current.strip():
                statements.append(current)
            current = ''
    if current.strip():
        raise ValueError('Incomplete SQL statement')
    return statements


def replay_migrations(migrations=None):
    """In-memory SQLite database built from every migration file."""
    connection = sqlite3.connect(':memory:')
    connection.execute('PRAGMA foreign_keys=ON')
    connection.execute('CREATE TABLE IF NOT EXISTS sports_ai_schema_migrations(name TEXT PRIMARY KEY, applied_at TEXT NOT NULL)')
    names = []
    for path in migrations or sorted(MIGRATIONS.glob('*.sql')):
        for statement in split_statements(path.read_text(encoding='utf-8')):
            connection.execute(statement)
        names.append(path.name)
    connection.commit()
    return connection, names


def schema_objects(connection):
    rows = connection.execute(
        "SELECT type, name, tbl_name, sql FROM sqlite_master WHERE sql IS NOT NULL AND name NOT LIKE 'sqlite_%'"
    ).fetchall()
    tables = [(name, sql) for kind, name, _t, sql in rows if kind == 'table']
    indexes = [(name, sql) for kind, name, _t, sql in rows if kind == 'index']
    triggers = [(name, sql) for kind, name, _t, sql in rows if kind == 'trigger']
    return tables, indexes, triggers


def seed_rows(connection):
    """Rows the migrations themselves insert (providers, schedules, policies, migration names...).

    Returns [(table, columns, rows)] for tables that are not empty after replaying the migrations.
    """
    tables, _indexes, _triggers = schema_objects(connection)
    seed = []
    for name, _sql in tables:
        cursor = connection.execute(f'SELECT * FROM "{name}"')
        rows = cursor.fetchall()
        if rows:
            seed.append((name, [column[0] for column in cursor.description], rows))
    return seed


def build_schema_statements(connection=None, foreign_keys_not_valid=False):
    """Ordered PostgreSQL DDL for the full current schema.

    Returns (statements, migration_names). Foreign keys are added after every table exists.
    """
    names = []
    if connection is None:
        connection, names = replay_migrations()
    tables, indexes, triggers = schema_objects(connection)
    statements = [table_ddl(sql) for _name, sql in tables]
    statements += [f'CREATE UNIQUE INDEX IF NOT EXISTS {name}_rowid ON {name} (rowid)' for name, _sql in tables]
    statements += [index_ddl(sql) for _name, sql in indexes]
    for name, _sql in tables:
        for _constraint, clause in foreign_key_ddl(connection, name, foreign_keys_not_valid):
            statements.append(clause)
    for _name, sql in triggers:
        statements += trigger_ddl(sql)
    return statements, names


def translate_migration(sql):
    """PostgreSQL statements for one later SQLite migration file (applied to an existing schema)."""
    out = []
    for statement in split_statements(sql):
        text = statement.strip()
        upper = text.upper()
        if upper.startswith('PRAGMA') or not text.rstrip(';').strip():
            continue
        if re.match(r'CREATE\s+TABLE', upper):
            out.append(table_ddl(text, with_foreign_keys=True))
            name = re.match(r'CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?"?(\w+)"?', text, re.I).group(1)
            out.append(f'CREATE UNIQUE INDEX IF NOT EXISTS {name}_rowid ON {name} (rowid)')
        elif re.match(r'CREATE\s+(UNIQUE\s+)?INDEX', upper):
            out.append(index_ddl(text))
        elif re.match(r'CREATE\s+TRIGGER', upper):
            out += trigger_ddl(text)
        elif re.match(r'ALTER\s+TABLE', upper):
            out.append(_outside_quotes(text.rstrip(';'), _types))
        else:
            out.append(text.rstrip(';'))
    return out
